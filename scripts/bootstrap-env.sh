#!/usr/bin/env bash
# Generate the secrets a local Docker Compose stack needs to run with authentication (#205).
#
# Writes, once:
#   .env                                    SSO_JWT_SECRET, the bootstrap admin key and the
#                                           Prometheus scrape key, read by docker-compose.yml
#   monitoring/secrets/prometheus-scrape-key the scrape key, read by monitoring/prometheus.yml
#
# Both are git-ignored. Re-running refuses to overwrite them unless --force is given, because
# replacing the keys locks out anything already configured with the old ones.
#
# Usage: scripts/bootstrap-env.sh [--force]
set -euo pipefail

cd "$(dirname "$0")/.."

ENV_FILE=.env
SCRAPE_FILE=monitoring/secrets/prometheus-scrape-key

if [[ "${1:-}" != "--force" ]] && { [[ -f "$ENV_FILE" ]] || [[ -f "$SCRAPE_FILE" ]]; }; then
  echo "Refusing to overwrite $ENV_FILE or $SCRAPE_FILE; pass --force to replace them." >&2
  exit 1
fi

command -v openssl >/dev/null || { echo "openssl is required" >&2; exit 1; }

# API keys are fsp_ (personal) or fss_ (service) plus 64 hex characters.
admin_key="fsp_$(openssl rand -hex 32)"
scrape_key="fss_$(openssl rand -hex 32)"
# The session signing secret must be at least 32 bytes and not a placeholder.
jwt_secret="$(openssl rand -base64 48 | tr -d '\n')"

umask 077
cat > "$ENV_FILE" <<EOF
# Generated by scripts/bootstrap-env.sh. Do not commit.
#
# Authentication is enforced (#209). SECURITY_ENFORCE_AUTH=false turns it off for local
# experiments only; SECURITY_WARN_MODE=true logs and counts refusals instead of refusing.
SECURITY_ENFORCE_AUTH=true
SECURITY_WARN_MODE=false
SSO_JWT_SECRET=${jwt_secret}
# Admin credential for first use. Create your real admin identity with it, then revoke it.
SECURITY_BOOTSTRAP_API_KEY=${admin_key}
# Carries only metrics:read. Prometheus presents it from ${SCRAPE_FILE}.
SECURITY_BOOTSTRAP_METRICS_API_KEY=${scrape_key}
EOF

mkdir -p "$(dirname "$SCRAPE_FILE")"
printf '%s' "$scrape_key" > "$SCRAPE_FILE"

echo "Wrote $ENV_FILE and $SCRAPE_FILE."
echo "Bootstrap admin key (also in $ENV_FILE): $admin_key"
echo "Next: docker compose up -d"
