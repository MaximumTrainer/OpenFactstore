#!/usr/bin/env node
// #250: the endpoint inventory. Reads docs/openapi.json (which OpenApiSnapshotTest keeps equal to
// the served API) and the duplicate decisions in tools/endpoint-inventory/decisions.json, and
// writes docs/api-inventory.md. The docs-drift tests fail when the committed inventory is stale.
//
//   node tools/endpoint-inventory/generate.mjs           # rewrite docs/api-inventory.md
//   node tools/endpoint-inventory/generate.mjs --check   # exit 1 if it is stale
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = fileURLToPath(new URL('.', import.meta.url))
const ROOT = join(HERE, '..', '..')
const METHODS = ['get', 'post', 'put', 'patch', 'delete']
const OUTPUT = 'docs/api-inventory.md'

export function loadInputs(root = ROOT) {
  return {
    openapi: JSON.parse(readFileSync(join(root, 'docs', 'openapi.json'), 'utf8')),
    decisions: JSON.parse(readFileSync(join(root, 'tools', 'endpoint-inventory', 'decisions.json'), 'utf8'))
  }
}

/** Every operation in the spec: { method, path, summary, deprecated }. Sorted by path, then method. */
export function operations(openapi) {
  return Object.entries(openapi.paths)
    .flatMap(([path, item]) => METHODS.filter((m) => item[m]).map((m) => ({
      method: m.toUpperCase(),
      path,
      summary: (item[m].summary ?? '').trim(),
      deprecated: item[m].deprecated === true
    })))
    .sort((a, b) => a.path.localeCompare(b.path) || METHODS.indexOf(a.method.toLowerCase()) - METHODS.indexOf(b.method.toLowerCase()))
}

const key = (o) => `${o.method} ${o.path}`

/** v1/v2 pairs with the same method and path: [["GET /api/v1/x", "GET /api/v2/x"], ...]. */
export function versionTwins(openapi) {
  const all = new Set(operations(openapi).map(key))
  return operations(openapi)
    .filter((o) => o.path.startsWith('/api/v1/'))
    .map((o) => [key(o), `${o.method} ${o.path.replace('/api/v1/', '/api/v2/')}`])
    .filter(([, twin]) => all.has(twin))
}

/** Operations the decisions deprecate. */
export function deprecatedByDecision(decisions) {
  return decisions.groups.filter((g) => g.decision === 'deprecate').flatMap((g) => g.deprecate)
}

/** The resource an operation belongs to: the first path segment after the version (and after commands/queries/admin). */
export function resourceOf(path) {
  const parts = path.split('/').filter(Boolean)
  if (parts[0] !== 'api') return parts[0] ?? '/'
  const rest = parts.slice(2)
  const first = rest[0] ?? ''
  if (['commands', 'queries', 'admin'].includes(first) && rest[1]) return `${first}/${rest[1]}`
  return first.replace(/[{}]/g, '')
}

function prefixOf(path) {
  const m = path.match(/^\/api\/(v\d+)\//)
  return m ? `/api/${m[1]}` : 'other'
}

const cell = (s) => String(s).replace(/\\/g, '\\\\').replace(/\|/g, '\\|')

export function renderInventory(openapi, decisions) {
  const ops = operations(openapi)
  const deprecated = ops.filter((o) => o.deprecated)
  const lines = []
  const out = (s = '') => lines.push(s)

  out('# API endpoint inventory')
  out()
  out('<!-- Generated by tools/endpoint-inventory/generate.mjs from docs/openapi.json and tools/endpoint-inventory/decisions.json. Do not edit by hand. -->')
  out()
  out('Every operation the backend serves, grouped by resource, with the decision taken on each set of duplicates (#250). ' +
    'Regenerate with `node tools/endpoint-inventory/generate.mjs`; the docs-drift tests fail when this file is stale, ' +
    'when a v1/v2 twin has no decision, or when the operations marked `deprecated` in the spec differ from the decisions.')
  out()
  out('## Summary')
  out()
  out('| | Operations |')
  out('|---|---:|')
  const prefixes = [...new Set(ops.map((o) => prefixOf(o.path)))].sort()
  for (const p of prefixes) out(`| \`${p}\` | ${ops.filter((o) => prefixOf(o.path) === p).length} |`)
  out(`| **Total** | **${ops.length}** |`)
  out(`| Deprecated | ${deprecated.length} |`)
  out(`| After the sunset on ${decisions.sunset} | ${ops.length - deprecated.length} |`)
  out()
  out(`Deprecated operations still work until the sunset. Every response from one carries \`Deprecation\`, \`Sunset\` and a ` +
    '`Link: <successor>; rel="successor-version"` header, and the OpenAPI document marks it `deprecated: true`. ' +
    'See [API deprecations](upgrading/api-deprecations.md) for how to move.')
  out()
  out('## Duplicates and decisions')
  out()
  const order = { deprecate: 0, 'deprecate-after-parity': 1, keep: 2 }
  const groups = [...decisions.groups].sort((a, b) => order[a.decision] - order[b.decision] || a.id.localeCompare(b.id))
  out('| Operations | Decision | Keep | Notes |')
  out('|---|---|---|---|')
  for (const g of groups) {
    const opsCell = g.operations.map((o) => `\`${o}\``).join('<br>')
    const keep = g.decision === 'deprecate' ? `\`${g.keep}\`` : 'all'
    const notes = [g.decision === 'deprecate' ? '' : g.reason, g.migration ?? ''].filter(Boolean).join(' ')
    out(`| ${opsCell} | ${g.decision} | ${keep} | ${cell(notes)} |`)
  }
  out()
  const reasons = [...new Set(groups.filter((g) => g.decision === 'deprecate').map((g) => g.reason))]
  for (const r of reasons) out(`Why the v1 twins are deprecated: ${r}`)
  out()
  out('## Finding unused routes')
  out()
  out('Request counts per route are in the `http_server_requests_seconds_count` metric at `/actuator/prometheus`, labelled by `method` and `uri` ' +
    '(the path template, as in the tables below). A route with no requests over a release cycle is a candidate for deprecation; ' +
    'record the decision in `tools/endpoint-inventory/decisions.json`.')
  out()
  out('## All operations by resource')
  const resources = [...new Set(ops.map((o) => resourceOf(o.path)))].sort()
  for (const r of resources) {
    out()
    out(`### ${r}`)
    out()
    out('| Method | Path | Summary | Status |')
    out('|---|---|---|---|')
    for (const o of ops.filter((x) => resourceOf(x.path) === r)) {
      out(`| ${o.method} | \`${o.path}\` | ${cell(o.summary)} | ${o.deprecated ? 'deprecated' : ''} |`)
    }
  }
  out()
  return lines.join('\n')
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { openapi, decisions } = loadInputs()
  const text = renderInventory(openapi, decisions)
  const path = join(ROOT, OUTPUT)
  if (process.argv.includes('--check')) {
    if (readFileSync(path, 'utf8') !== text) {
      console.error(`${OUTPUT} is stale; run: node tools/endpoint-inventory/generate.mjs`)
      process.exit(1)
    }
  } else {
    writeFileSync(path, text)
    console.log(`wrote ${OUTPUT}`)
  }
}
